"""
TesseraID — performance-tuned Python implementation.

Optimizations vs. the canonical tessera_id.py:
  - struct.pack for fixed-width binary serialization (faster than int.to_bytes)
  - Pre-bound module functions (urandom, monotonic_ns, time_ns)
  - Bytearray buffer + memoryview slicing to reduce allocation count
  - Counter step generated by a single 32-byte urandom() call shared with the
    random field where possible (one syscall per ID instead of two)
  - Inlined hot path; no per-call dataclass construction

Public API mirrors tessera_id.py: new(), new_hlc().
"""

from __future__ import annotations

import os
import struct
import threading
import time
from typing import Optional

# Shared error taxonomy: raise the SAME exception classes as the canonical
# reference so callers can catch tessera_id.* types regardless of which
# implementation produced the error (TP-035 / TID-00017).
from tessera_id import (  # noqa: F401  (re-exported as public API)
    HLCDriftError,
    InvalidEncoding,
    TesseraIDError,
    UnknownVariant,
)

# Implementation version (TID-00022) — kept identical to tessera_id.__version__.
__version__ = "1.3.1"

VARIANT_STANDARD = 0x01
VARIANT_HLC = 0x02
TESSERA_ID_SIZE = 41
RAND_SIZE = 32
MAX_COUNTER = 0xFFFF
HLC_MAX_DRIFT_MS = 60_000

# Pre-bound for hot path
_urandom = os.urandom
_time_ns = time.time_ns
# struct format: 6-byte timestamp via 2-byte high + 4-byte low,
# then 1-byte variant, then 2-byte counter. 9 bytes total of header.
_pack_header = struct.Struct(">HIBH").pack


def _now_ms() -> int:
    return _time_ns() // 1_000_000


class StandardGenerator:
    __slots__ = ("_last_ts", "_counter")

    def __init__(self) -> None:
        self._last_ts = 0
        self._counter = 0

    def new(self) -> bytes:
        ts = _now_ms()
        if ts < self._last_ts:
            ts = self._last_ts

        # Single urandom() call for both counter step (1 byte) and random tail
        # (32 bytes). Saves one syscall vs. two separate calls.
        rnd = _urandom(RAND_SIZE + 1)

        if ts == self._last_ts:
            step = 1 + (rnd[0] & 0x0F)
            counter = self._counter + step
            if counter > MAX_COUNTER:
                # Spin until the wall clock strictly exceeds last_ts (spec
                # sec03: `while now_ms() <= last_ts`). Equality-only spin
                # would exit immediately after a clock regression and emit
                # a regressed timestamp.
                while _now_ms() <= self._last_ts:
                    pass
                ts = _now_ms()
                counter = rnd[0]
        else:
            counter = rnd[0]

        self._last_ts = ts
        self._counter = counter

        ts_hi = (ts >> 32) & 0xFFFF
        ts_lo = ts & 0xFFFFFFFF
        return _pack_header(ts_hi, ts_lo, VARIANT_STANDARD, counter) + rnd[1:]


class HLCGenerator:
    __slots__ = ("_l", "_c", "_lock")

    def __init__(self) -> None:
        self._l = 0
        self._c = 0
        self._lock = threading.Lock()

    def new(self, observe: Optional[bytes] = None) -> bytes:
        rnd = _urandom(RAND_SIZE)
        with self._lock:
            pt = _now_ms()
            l_old, c_old = self._l, self._c

            if observe is not None:
                if len(observe) != TESSERA_ID_SIZE:
                    raise InvalidEncoding(f"observe must be {TESSERA_ID_SIZE} bytes")
                l_msg = int.from_bytes(observe[0:6], "big")
                c_msg = int.from_bytes(observe[7:9], "big")

                if l_msg - pt > HLC_MAX_DRIFT_MS:
                    raise HLCDriftError(
                        f"observed HLC {l_msg - pt}ms ahead of physical clock"
                    )

                l_new = max(l_old, l_msg, pt)
                if l_new == l_old == l_msg:
                    c_new = max(c_old, c_msg) + 1
                elif l_new == l_old:
                    c_new = c_old + 1
                elif l_new == l_msg:
                    c_new = c_msg + 1
                else:
                    c_new = 0
            else:
                l_new = max(l_old, pt)
                c_new = c_old + 1 if l_new == l_old else 0

            if c_new > MAX_COUNTER:
                l_new += 1
                c_new = 0

            self._l, self._c = l_new, c_new

        ts_hi = (l_new >> 32) & 0xFFFF
        ts_lo = l_new & 0xFFFFFFFF
        return _pack_header(ts_hi, ts_lo, VARIANT_HLC, c_new) + rnd


# Module-level convenience
_default_std = StandardGenerator()
_default_std_lock = threading.Lock()
_default_hlc = HLCGenerator()


def new() -> bytes:
    with _default_std_lock:
        return _default_std.new()


def new_hlc(observe: Optional[bytes] = None) -> bytes:
    return _default_hlc.new(observe=observe)
