/*
 * fuzz_decrypt.c — libFuzzer harness for the TesseraSeal C reference
 * (TESS-00016 / TP-096).
 *
 * The C reference is the canonical ABI and does manual offset arithmetic
 * over the attacker-controlled KEM_CT_LEN / AD_LEN header fields, so this
 * is the highest-value fuzz surface in the repo. The harness drives:
 *
 *   - tessera_seal_peek_header()  (structural decode)
 *   - tessera_seal_peek_ad()      (zero-copy AD slicing — offset arithmetic)
 *   - tessera_seal_decrypt()      (full decode + constant-time auth path)
 *     against a static suite-0x01 key, twice: once on the raw input and
 *     once with variant/suite pinned to valid values so the fuzzer spends
 *     its budget past the cheap structural rejects.
 *
 * Contract: never crash (ASan-clean), never read/write out of bounds, and
 * never report success with a plaintext that is not strictly shorter than
 * the envelope. Authentication-class failures all map to
 * TESSERA_SEAL_E_DECRYPT_FAILED; this harness only checks memory safety and
 * the success postcondition — error-code semantics are KAT territory.
 *
 * Build + run (needs a clang with the libFuzzer runtime — Apple's Xcode
 * clang does not ship it; Homebrew LLVM does):
 *
 *   cd tessera-seal/c && make fuzz          # 60 s wall + 50k-iteration run
 *   make fuzz FUZZ_TIME=600 FUZZ_RUNS=1000000
 */
#include <stdint.h>
#include <stdlib.h>
#include <string.h>

#include "tessera_seal.h"

static tessera_seal_priv_t g_priv;
static int g_ready = 0;

int LLVMFuzzerInitialize(int *argc, char ***argv);
int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size);

int LLVMFuzzerInitialize(int *argc, char ***argv) {
    (void)argc;
    (void)argv;
    /* Static fuzz key. Random per process (the C ABI exposes no seeded
     * keygen); corpus entries that depend on the key are regenerated by the
     * seed step in `make fuzz`, every other input is key-independent. */
    tessera_seal_pub_t pub;
    if (tessera_seal_generate_keypair(TESSERA_SEAL_SUITE_MLKEM1024_AESGCM,
                                      &g_priv, &pub) == TESSERA_SEAL_OK) {
        g_ready = 1;
    }
    return 0;
}

static void try_decrypt(const uint8_t *env, size_t env_len) {
    size_t cap = env_len ? env_len : 1;
    uint8_t *out = (uint8_t *)malloc(cap);
    if (out == NULL) {
        return;
    }
    size_t out_len = cap;
    int rc = tessera_seal_decrypt(env, env_len, &g_priv, NULL, 0,
                                  out, cap, &out_len);
    if (rc == TESSERA_SEAL_OK && out_len >= env_len) {
        /* Plaintext must be strictly shorter than its envelope. */
        abort();
    }
    free(out);
}

int LLVMFuzzerTestOneInput(const uint8_t *data, size_t size) {
    tessera_seal_header_t h;
    int hrc = tessera_seal_peek_header(data, size, &h);
    if (hrc == TESSERA_SEAL_OK) {
        if (h.variant != TESSERA_SEAL_VARIANT ||
            h.kem_ct_len > TESSERA_SEAL_MAX_KEM_CT_LEN ||
            h.ad_len > TESSERA_SEAL_MAX_AD_LEN) {
            /* peek_header accepted a header it documents as rejected. */
            abort();
        }
    }

    const uint8_t *ad = NULL;
    uint32_t ad_len = 0;
    int arc = tessera_seal_peek_ad(data, size, &ad, &ad_len);
    if (arc == TESSERA_SEAL_OK) {
        if (hrc != TESSERA_SEAL_OK) {
            /* peek_ad accepted what peek_header rejected. */
            abort();
        }
        if ((size_t)TESSERA_SEAL_HEADER_BYTES + h.kem_ct_len + ad_len > size) {
            /* AD slice extends past the envelope end. */
            abort();
        }
        /* Touch every AD byte so ASan validates the zero-copy slice. */
        uint8_t acc = 0;
        for (uint32_t i = 0; i < ad_len; i++) {
            acc ^= ad[i];
        }
        (void)acc;
    }

    if (!g_ready) {
        return 0;
    }

    try_decrypt(data, size);

    /* Pin variant/suite so the fuzzer reaches the KEM_CT_LEN / AD_LEN
     * offset arithmetic and the constant-time synthetic-key auth path. */
    if (size >= TESSERA_SEAL_HEADER_BYTES) {
        uint8_t *mut_env = (uint8_t *)malloc(size);
        if (mut_env != NULL) {
            memcpy(mut_env, data, size);
            mut_env[TESSERA_SEAL_VARIANT_OFFSET] = TESSERA_SEAL_VARIANT;
            mut_env[TESSERA_SEAL_SUITE_OFFSET] = TESSERA_SEAL_SUITE_MLKEM1024_AESGCM;
            try_decrypt(mut_env, size);
            free(mut_env);
        }
    }
    return 0;
}
